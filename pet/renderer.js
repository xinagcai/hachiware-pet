/* The skin strip is a single row that scrolls sideways. Deleting a skin takes
   two clicks (the button arms itself), so no dialog is needed on either shell. */
const renderSkins = () => {
  const skinState = snapshot.skin || {};
  const options = Array.isArray(skinState.options) ? skinState.options : [];
  const signature = `${skinState.slug}|${options.map((option) => `${option.slug}:${option.name}`).join(',')}`;
  if (signature === skinsSignature) return;
  skinsSignature = signature;
  skinsBox.textContent = '';
  for (const option of options) {
    const chip = document.createElement('div');
    chip.className = `chip${option.slug === skinState.slug ? ' active' : ''}`;

    const name = document.createElement('button');
    name.type = 'button';
    name.className = 'chip-name';
    name.textContent = option.name;
    name.title = `切换到 ${option.name}`;
    name.addEventListener('click', (event) => {
      event.stopPropagation();
      if (suppressChipClick) {
        suppressChipClick = false;
        return;
      }
      if (option.slug === (snapshot.skin || {}).slug) return;
      if (api.switchSkin) api.switchSkin(option.slug);
      flash(`切换到 ${option.name}…`, 1500);
    });

    const remove = document.createElement('button');
    remove.type = 'button';
    remove.className = 'chip-del';
    remove.textContent = '×';
    remove.title = `删除 ${option.name}（再点一次确认）`;
    remove.addEventListener('click', (event) => {
      event.stopPropagation();
      if (suppressChipClick) {
        suppressChipClick = false;
        return;
      }
      const now = Date.now();
      if (armedSkin.slug === option.slug && now < armedSkin.until) {
        armedSkin = { slug: '', until: 0 };
        if (api.deleteSkin) api.deleteSkin(option.slug);
        remove.className = 'chip-del';
        remove.textContent = '×';
        flash(`已删除 ${option.name}`, 2000);
        return;
      }
      armedSkin = { slug: option.slug, until: now + 2500 };
      for (const other of skinsBox.querySelectorAll('.chip-del.armed')) {
        other.className = 'chip-del';
        other.textContent = '×';
      }
      remove.className = 'chip-del armed';
      remove.textContent = '删?';
      setTimeout(() => {
        if (armedSkin.slug !== option.slug) return;
        armedSkin = { slug: '', until: 0 };
        if (remove.isConnected) {
          remove.className = 'chip-del';
          remove.textContent = '×';
        }
      }, 2500);
    });

    chip.append(name, remove);
    skinsBox.appendChild(chip);
  }
  skinsBox.hidden = options.length === 0;
};


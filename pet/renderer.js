const render = () => {
  const current = mood();
  pet.className = current + (drag ? ' dragging' : '');
  paintArt(current);

  const approvals = snapshot.approvals.length;
  if (approvals > 0) {
    badge.hidden = false;
    badge.textContent = String(approvals);
  } else {
    badge.hidden = true;
  }

  setSkinUi();
  renderSkins();
  if (!searchBox.hidden) renderSearch();
  const showToast = Boolean(toastText) && Date.now() < toastUntil;
  toast.hidden = !showToast;
  if (showToast) toast.textContent = toastText;
  placeToast();

  const running = snapshot.sessions.filter((session) => session.running).length;
  let summary = snapshot.sessions.length === 0
    ? '还没有会话'
    : `会话 ${snapshot.sessions.length} · 运行 ${running} · 待批 ${approvals}`;
  if (!(snapshot.skin && snapshot.skin.ready) && !skin) summary += ' · 点「装皮肤」';
  if (snapshot.skin && snapshot.skin.installing) summary += ' · 正在下载皮肤';
  summaryText.textContent = summary;

  // Rebuild the rows only when identities, order, or state actually change, so
  // scrolling and hover survive the 1.2s status push.
  const signature = snapshot.sessions
    .map((session) => `${session.id}:${sessionState(session)}:${session.title || ''}:${session.approval?.toolName || ''}`)
    .join('|');
  if (signature !== rowsSignature) {
    rowsSignature = signature;
    renderRows();
  } else {
    // Durations keep ticking between rebuilds without touching scroll or hover.
    for (const session of snapshot.sessions) {
      const meta = metaBySession.get(session.id);
      const text = metaText(session);
      if (meta && meta.textContent !== text) meta.textContent = text;
    }
  }
  reportHitbox();
};

const setPanel = (open) => {
  if (!open) closeSearch();
  panelOpen = open;
  panel.hidden = !open;
  if (open) render();
  placeToast();
  reportHitbox();
};

function reportHitbox() {
  if (!nativeBridge) return;
  const rect = (element) => {
    const box = element.getBoundingClientRect();
    return { x: box.left, y: box.top, w: box.width, h: box.height };
  };
  nativeBridge.postMessage({ type: 'hitbox', pet: rect(pet), panel: panelOpen ? rect(panel) : null });
}


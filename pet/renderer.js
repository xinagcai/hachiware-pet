const sessionState = (session) => (session.approval ? 'approval' : session.running ? 'running' : 'idle');

const mood = () => {
  if (snapshot.approvals.length > 0) return 'alert';
  const running = snapshot.sessions.filter((session) => session.running);
  if (running.length === 0) return 'idle';
  const longest = Math.max(...running.map((session) => session.runningMs || 0));
  if (longest < 5 * 60 * 1000) return 'focused';
  if (longest < 15 * 60 * 1000) return 'strained';
  return 'tired';
};

const formatDuration = (ms) => {
  const total = Math.max(0, Math.floor(ms / 1000));
  const minutes = Math.floor(total / 60);
  if (minutes >= 60) return `${Math.floor(minutes / 60)}h${minutes % 60}m`;
  if (minutes > 0) return `${minutes}m${total % 60}s`;
  return `${total}s`;
};

const metaText = (session) => {
  const state = sessionState(session);
  if (state === 'approval') return `等待审批${session.approval?.toolName ? ` · ${session.approval.toolName}` : ''}`;
  if (state === 'running') return formatDuration(session.runningMs || 0);
  return '空闲';
};


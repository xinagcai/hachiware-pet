const skinOpt = (key, fallback) => {
  const value = skin && skin.config && skin.config[key];
  return value === undefined || value === null ? fallback : value;
};
const skinCell = () => {
  const cell = skinOpt('cell', {}) || {};
  return { width: Number(cell.width) || 192, height: Number(cell.height) || 208 };
};
const skinColumns = () => Math.max(1, Number(skinOpt('columns', 8)) || 8);
const skinRows = () => Math.max(1, Number(skinOpt('rows', 9)) || 9);
const skinFps = () => Math.max(2, Math.min(24, Number(skinOpt('fps', 8)) || 8));
const skinRow = (state) => {
  const moods = skinOpt('moods', {}) || {};
  const row = Number(moods[state]);
  return Number.isInteger(row) && row >= 0 ? Math.min(row, skinRows() - 1) : 0;
};

// A skin whose image cannot be decoded must not leave an empty pet behind.

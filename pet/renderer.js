// A skin is injected at runtime by the native window: it reads the sprite from
// ~/Library/Application Support/dsh-hachiware-pet/skins and hands over a data
// URL, because a file:// page cannot fetch a sibling file under sandbox rules.
const applySkin = (payload) => {
  if (!payload || !payload.dataUrl) return;
  skin = {
    config: payload.config || {},
    frames: Array.isArray(payload.frames) ? payload.frames : null,
    url: payload.dataUrl,
  };
  skinBroken = false;
  rowFrames = null;
  spriteRow = -1;
  spriteFrame = 0;
  stopSprite();
  const probe = new Image();
  probe.onload = () => {
    rowFrames = skinOpt('frames', null)
      || (skin.frames && skin.frames.length === skinRows() ? skin.frames : null)
      || detectRowFrames(probe);
    reportDebug(`skin loaded ${probe.naturalWidth}x${probe.naturalHeight} frames ${JSON.stringify(rowFrames)}`);
    try {
      paintArt(mood());
    } catch {
      /* the next state push repaints */
    }
  };
  probe.onerror = () => {
    skinBroken = true;
    reportDebug('skin image failed to load');
    paintArt(mood());
  };
  probe.src = skin.url;
  if (typeof render === 'function') render();

// Development builds may still inline a skin through skin.js; the market bundle
// ships none and relies on the native runtime injection instead.
if (window.__PET_SKIN && window.__PET_SKIN.dataUrl) applySkin(window.__PET_SKIN);
};


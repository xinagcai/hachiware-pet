/* ------------------------------------------------------------------ state */

api.onState((next) => {
  const previous = lastApprovalCount;
  snapshot = next || { sessions: [], approvals: [] };
  lastApprovalCount = (snapshot.approvals || []).length;

  const skinState = snapshot.skin || {};
  if (skinState.ready && skinState.version && skinState.version !== lastSkinVersion) {
    const first = lastSkinVersion === '';
    lastSkinVersion = skinState.version;
    flash(first ? '皮肤已就绪' : '皮肤已更新');
  }
  if (lastApprovalCount > previous) {
    chime();
    if (!panelOpen) setPanel(true);
  }
  render();
  if (panelOpen) render();
});

render();

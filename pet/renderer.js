const isOver = (element, x, y) => {
  const rect = element.getBoundingClientRect();
  return x >= rect.left - 4 && x <= rect.right + 4 && y >= rect.top - 4 && y <= rect.bottom + 4;
};

let interactive = false;
const setInteractive = (flag) => {
  if (flag === interactive) return;
  interactive = flag;
  api.interactive(flag);
};

// The window is click-through by default. macOS forwards mouse moves even in
// that mode, so hovering the pet (or an open panel) is what makes the window
// accept real clicks.
window.addEventListener('mousemove', (event) => {
  const overPet = isOver(pet, event.clientX, event.clientY);
  const overPanel = panelOpen && isOver(panel, event.clientX, event.clientY);
  setInteractive(overPet || overPanel);
});

window.addEventListener('mouseleave', () => setInteractive(false));


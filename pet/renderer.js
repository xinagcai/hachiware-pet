/* Swipe the strip with the mouse (touch already scrolls natively) and let the
   wheel travel horizontally while the pointer is over it. */
let skinScroll = null;
skinsBox.addEventListener('pointerdown', (event) => {
  if (event.button !== 0 || event.pointerType === 'touch') return;
  skinScroll = {
    id: event.pointerId,
    x: event.clientX,
    left: skinsBox.scrollLeft,
    moved: false,
  };
});
document.addEventListener('pointermove', (event) => {
  if (!skinScroll || event.pointerId !== skinScroll.id) return;
  const dx = event.clientX - skinScroll.x;
  if (!skinScroll.moved && Math.abs(dx) < 4) return;
  if (!skinScroll.moved) {
    skinScroll.moved = true;
    skinsBox.classList.add('dragging');
  }
  skinsBox.scrollLeft = skinScroll.left - dx;
  event.preventDefault();
});
const finishSkinScroll = (event) => {
  if (!skinScroll || event.pointerId !== skinScroll.id) return;
  suppressChipClick = skinScroll.moved;
  skinsBox.classList.remove('dragging');
  skinScroll = null;
  if (suppressChipClick) setTimeout(() => { suppressChipClick = false; }, 0);
};
document.addEventListener('pointerup', finishSkinScroll);
document.addEventListener('pointercancel', finishSkinScroll);
skinsBox.addEventListener('wheel', (event) => {
  if (Math.abs(event.deltaX) > Math.abs(event.deltaY)) return;
  if (skinsBox.scrollWidth <= skinsBox.clientWidth) return;
  skinsBox.scrollLeft += event.deltaY;
  event.preventDefault();
}, { passive: false });

/* The Windows shell cannot deliver keyboard events to a click-through
   WebView2, so it replays typed characters here instead. */
window.__petKey = (kind, text) => {
  const field = document.activeElement;
  if (!field || typeof field.value !== 'string') return;
  if (kind === 'char') {
    field.value += text;
    field.dispatchEvent(new Event('input', { bubbles: true }));
  } else if (kind === 'back') {
    field.value = field.value.slice(0, -1);
    field.dispatchEvent(new Event('input', { bubbles: true }));
  } else {
    field.blur();
  }
};

